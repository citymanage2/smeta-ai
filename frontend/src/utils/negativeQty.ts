/**
 * Позиция с отрицательным объёмом — вычет, а не работа.
 *
 * В перечнях и сметах встречаются строки вида «на каждые 10 мм изменения
 * глубины сверления добавляется −0,61»: они корректируют объём соседней
 * позиции. Считать по ним стоимость нельзя — `qty × цена` даёт отрицательную
 * сумму, которая занижает итог сметы.
 *
 * Правило одно на весь фронтенд и совпадает с backend
 * (`app/utils/price_coercion.py`: `is_negative_qty` / `coerce_qty`):
 * цену по такой строке не ищем, стоимость не считаем, строку оставляем как есть.
 */

/** Объём меньше нуля — по строке ничего не считаем. */
export const isNegativeQty = (qty: number | null | undefined): boolean =>
  qty != null && qty < 0;

/**
 * Объём для умножения на цену: вычет и пустое значение дают 0.
 *
 * Зеркало `coerce_qty` на backend — иначе итог в интерфейсе разойдётся с
 * итогом в выгруженном xlsx.
 */
export const billableQty = (qty: number | null | undefined): number =>
  qty != null && qty > 0 ? qty : 0;
