/**
 * Объём позиции — дробное число: 0,61 «100 отверстий», 1,1139 т, 137,3 м.
 *
 * Раньше сетка печатала его через `Math.round`, и 0,61 показывалось как «1»:
 * по такой смете нельзя ни проверить расчёт, ни увидеть вычет вида −0,61.
 * Деньги округлять до рубля осмысленно, объём — нет.
 *
 * Показываем как есть, до 6 знаков после запятой, без хвостовых нулей
 * (`toLocaleString` их не печатает).
 */
export const formatQty = (n: number): string =>
  n.toLocaleString('ru-RU', { maximumFractionDigits: 6 });
