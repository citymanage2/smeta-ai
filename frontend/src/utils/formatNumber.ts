/**
 * Как числа показываются в таблице редактора.
 *
 * В смете принят русский формат: разряды отбиты пробелом, дробная часть — через
 * запятую. Раньше таблица печатала значение как есть (`196171.2`), и сумму
 * нельзя было прочитать, не пересчитав нули.
 *
 * ВАЖНО: форматирование живёт только на показе. В строке таблицы значение
 * остаётся числом, иначе отформатированная строка ушла бы в выгрузку и ячейка
 * Excel стала бы текстовой — колонку в файле не просуммировать.
 */

const MONEY = new Intl.NumberFormat('ru-RU', {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

const DECIMAL = new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 6 });

/** Деньги: `1 111 111,11` — всегда две цифры после запятой. */
export function formatMoney(value: number): string {
  return MONEY.format(value);
}

/**
 * Объём и прочие дробные числа: запятая, разряды пробелом, до 6 знаков без
 * хвостовых нулей. Округлять объём до целого нельзя — 0,61 «100 отверстий»
 * превратилось бы в 1.
 */
export function formatDecimal(value: number): string {
  return DECIMAL.format(value);
}
