import { isNegativeQty } from '../../utils/negativeQty';
import { GridRow, toNumber } from './adapters/types';

/**
 * Скрытие строк-вычетов — строк с отрицательным объёмом
 * (план `plans/2026-09-02-skrytie-strok-s-minusom.md`).
 *
 * В чужих сметах попадаются строки вида «на каждые 10 мм изменения глубины
 * сверления −0,61»: они корректируют объём соседней позиции, а не являются
 * работой или материалом. Стоимости у них нет — ни на экране, ни в файле
 * (`billableQty`, на сервере `coerce_qty`), — но в таблице они стоят наравне с
 * позициями и мешают читать документ.
 *
 * Главное правило то же, что у свёртки: **скрытие — уровень показа, а не
 * изменение документа.** Строки остаются в состоянии редактора, поэтому
 * «Применить», итоги, история, откат и журнал корректировок работают одинаково
 * в обоих режимах.
 *
 * Что считать отрицательным объёмом, решает `isNegativeQty` — одно правило на
 * весь фронтенд и зеркало серверного `price_coercion.is_negative_qty`. Своего
 * сравнения `< 0` здесь нет намеренно: две копии правила однажды разошлись бы.
 */

/**
 * Строка-вычет: в колонке объёма число меньше нуля.
 *
 * Строка принимается любая плоская — и строка таблицы, и строка выгрузки:
 * правило смотрит на одну ячейку, и заводить ради него вторую функцию значило
 * бы завести вторую копию правила.
 */
export function isDeductionRow(row: Record<string, unknown>, qtyKey: string): boolean {
  return isNegativeQty(toNumber(row[qtyKey]));
}

/**
 * Сколько строк-вычетов в наборе.
 *
 * Нужно и для числа на кнопке, и для того, чтобы кнопка была недоступна, когда
 * прятать нечего: включённый режим, который ничего не изменил, выглядит как
 * поломка.
 */
export function countDeductions(rows: GridRow[], qtyKey: string): number {
  let count = 0;
  for (const row of rows) if (isDeductionRow(row, qtyKey)) count += 1;
  return count;
}

/** Строки без вычетов. Порядок остальных строк не меняется. */
export function hideDeductionRows(rows: GridRow[], qtyKey: string): GridRow[] {
  return rows.filter((row) => !isDeductionRow(row, qtyKey));
}
