import React from 'react';

/**
 * Подсказка при наведении — своя, а не системная.
 *
 * `title` браузера всплывает через секунду, показывается системным шрифтом и
 * не появляется вовсе на выключенной кнопке — а именно у выключенной кнопки
 * подсказка нужнее всего: она объясняет, почему кнопка недоступна («Сначала
 * примените правки», «Отметьте строки галочками»). Обёртка ловит наведение
 * сама, поэтому работает и с `disabled`.
 *
 * Доступное имя кнопки при этом остаётся на самой кнопке (`aria-label`):
 * подсказка — это оформление, а не имя элемента.
 */
interface Props {
  /** Полное описание действия. Пусто — обёртки нет вовсе. */
  text?: string | false | null;
  /**
   * Куда прижимать пузырь. У правого края тулбара подсказка по центру уезжает
   * за пределы окна и обрезается — там `end`.
   */
  align?: 'start' | 'center' | 'end';
  children: React.ReactNode;
}

export const Hint: React.FC<Props> = ({ text, align = 'center', children }) => {
  if (!text) return <>{children}</>;
  return (
    <span className={`de-hint de-hint-${align}`} data-hint={text}>
      {children}
    </span>
  );
};

export default Hint;
