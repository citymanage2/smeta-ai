"""Прогноз времени по задаче — общая форма ответа для очереди, карточки и канбана."""
from typing import Optional

from pydantic import BaseModel


class TaskEta(BaseModel):
    """Оценка, а не обещание: в интерфейсе всегда показывается с «≈»."""

    # Сколько ждать старта обработки (0 — задача уже считается).
    starts_in_s: int
    # Сколько ждать результата с этого момента (включая ожидание в очереди).
    ready_in_s: int
    # То же в абсолютном времени (UTC ISO) — чтобы фронт показал «≈ 14:10».
    ready_at: str
    # True — прогноз грубый: нет замеренного объёма или ещё нет истории по типу.
    rough: bool
    # True — расчётное время вышло, а задача ещё идёт: показываем «завершается».
    finishing: bool
    # Что и в чём померили: 1200 «items», 48 «pages», 300 «rows».
    units: Optional[int] = None
    unit_kind: Optional[str] = None
    # Место в очереди на запуск: 1 — следующая. None — задача уже считается (или
    # ждёт ответа Batch API и слот не занимает). Нужна отдельно от `starts_in_s`:
    # «третья в очереди» — это факт, а минуты ожидания — оценка, и на вопрос
    # «меня вообще скоро возьмут?» отвечает именно факт.
    queue_position: Optional[int] = None
