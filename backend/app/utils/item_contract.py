"""Контракт позиции: набор полей, на который вправе рассчитывать потребитель.

Позиции перечня и полноты приходят из ответа ИИ и складываются в
`task.progress_data['items']` как есть. Ответ ИИ — не наш код: поле, которое он
обязан вернуть, он иногда не возвращает вовсе. Дырка живёт молча до первого
потребителя, который берёт поле по ключу, — а это шаг расчёта цен в смете,
после половины оплаченных чанков.

Поэтому позиция приводится к контракту в двух местах: когда ответ ИИ становится
позициями задачи и когда смета читает чужие позиции. Второе важнее: оно чинит и
те задачи, что уже лежат в базе с дырявыми строками.

Значения не трогаются — дописываются только отсутствующие ключи. Пустая единица
законна (см. CLAUDE.md, правило 8: «Единица не указана — берём как есть»), а вот
отсутствующая — авария на ровном месте.
"""
from __future__ import annotations

from typing import Any

# Поля, которые потребитель берёт по ключу: тип, наименование, единица, объём.
_TEXT_FIELDS = ("type", "name", "unit")
_NULLABLE_FIELDS = ("quantity",)


def ensure_item_fields(items: list[Any]) -> list[Any]:
    """Дописать отсутствующие поля позиции. Возвращает новый список.

    Не-словари пропускаются как есть: разбираться с ними — дело потребителя,
    а не этого контракта.
    """
    result: list[Any] = []
    for item in items or []:
        if not isinstance(item, dict):
            result.append(item)
            continue
        filled = dict(item)
        for field in _TEXT_FIELDS:
            if filled.get(field) is None:
                filled[field] = ""
        for field in _NULLABLE_FIELDS:
            filled.setdefault(field, None)
        result.append(filled)
    return result
