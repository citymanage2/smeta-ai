"""Позиция сметы не должна принимать себя за итоговую строку.

Было: `_TOTAL_KEYWORDS` искал служебные аббревиатуры без границы слова слева, и
`сп\\b` совпадало внутри «исп.» — сокращения «исполнение», которое стоит в
наименовании почти любого оборудования ОПС и автоматики. Позиция ЛСР
«Контроллер … Панель-2-ПРО (S3) исп.Л» отбрасывалась ещё до отправки чанка в
Claude: ИИ её не видел, в перечне её не было, и пропуск ничем не проявлялся.

Стало: служебное слово — это целое слово, а строка с номером в «№ п/п»,
единицей измерения и объёмом итоговой не считается никогда.

План: plans/2026-08-14-propusk-pozicij-iz-grand-smety.md
"""
import io

import openpyxl

from app.utils.file_parser import parse_xlsx_grand


_HEADER = [
    "№ п/п", "Обоснование", "Наименование работ и затрат", "Единица измерения",
    "Количество", "коэффициенты", "всего с учетом коэффициентов",
    "Сметная стоимость, руб.",
]


def _lsr(rows: list[list]) -> bytes:
    """Фрагмент ЛСР в раскладке ГРАНД-Сметы: шапка, раздел, переданные строки."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.append(["ЛОКАЛЬНЫЙ СМЕТНЫЙ РАСЧЕТ (СМЕТА) № 1"])
    ws.append(_HEADER)
    ws.append(["Раздел 1. Оборудование"])
    for row in rows:
        ws.append(row)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def _names(data: bytes) -> list[str]:
    return [r["name"] for r in parse_xlsx_grand(data) if not r["is_section"]]


def _fire_alarm_section() -> bytes:
    """Раздел «Оборудование» пожарной сигнализации — тот самый случай из жалобы."""
    return _lsr([
        [2, "ГЭСНм10-08-001-11", "Устройства промежуточные на количество лучей: 10",
         "шт", 1, 1, 1, None],
        [None, None, "Итого прямые затраты", None, None, None, None, 6732.0],
        ["2.1", "421/пр_2020_п.75_пп.а", "Вспомогательные ненормируемые материальные ресурсы",
         "%", 2, None, 2, None],
        [None, None, "Всего по позиции", None, None, None, None, 6732.0],
        ["3\nО", "ТЦ_89.1.61.02_66_6670465-193_27.11.2025_01_1.3",
         "Контроллер радиоканальных и проводных устройств Панель-2-ПРО (S3) исп.Л",
         "шт", 1, 1, 1, 35182.38],
        [None, None, "Всего по позиции", None, None, None, None, 35182.38],
        [4, "ГЭСНм10-08-002-02",
         "Извещатель ПС автоматический: дымовой, фотоэлектрический, радиоизотопный, "
         "световой в нормальном исполнении", "шт", 113, 1, 113, None],
        [None, None, "Всего по позиции", None, None, None, None, 14000.0],
        ["5\nО", "ТЦ_89.1.61.02_66_6670465-193_27.11.2025_01_1.4",
         "Извещатель пожарный дымовой оптико-электронный ИП 212-141 исп.01",
         "шт", 113, 1, 113, 56500.0],
        [None, None, "Всего по позиции", None, None, None, None, 56500.0],
    ])


def test_equipment_with_ispolnenie_reaches_the_list():
    """«исп.Л» — исполнение, а не «СП»: позиция остаётся."""
    names = _names(_fire_alarm_section())

    assert "Контроллер радиоканальных и проводных устройств Панель-2-ПРО (S3) исп.Л" in names


def test_material_of_the_next_work_reaches_the_list():
    """Сами извещатели — отдельная позиция ЛСР, и она тоже доезжает."""
    names = _names(_fire_alarm_section())

    assert "Извещатель пожарный дымовой оптико-электронный ИП 212-141 исп.01" in names


