def test_names_from_the_real_price_list_survive():
    """Наименования из корпоративного прайса фильтр не трогает.

    «ЦСП» и «ДСП» кончаются на «сп», «светильники накладные» начинаются с
    «накладн» — на 657 позициях прайса старый фильтр выбрасывал шесть таких.
    """
    names = _names(_lsr([
        [1, "ФССЦ-1", "Плита ЦСП 3200х1250х10 мм Тамак", "м2", 12, 1, 12, 4300.0],
        [2, "ФССЦ-2", "Монтаж перегородок из ДВП, ДСП", "м2", 8, 1, 8, 2100.0],
        [3, "ФЕР-3", "Монтаж светильников накладных, линейных", "шт", 20, 1, 20, 9000.0],
    ]))

    assert names == [
        "Плита ЦСП 3200х1250х10 мм Тамак",
        "Монтаж перегородок из ДВП, ДСП",
        "Монтаж светильников накладных, линейных",
    ]


def test_position_with_service_word_in_name_survives():
    """Номер + единица + объём — это позиция, что бы ни стояло в наименовании.

    Наименование позиции может ссылаться на свод правил («по СП 484.1311500»)
    или содержать «в том числе» — фильтр служебных строк её не касается.
    """
    names = _names(_lsr([
        [8, "ГЭСНм10-08-003-01", "Монтаж системы оповещения по СП 484.1311500.2020",
         "шт", 4, 1, 4, 12000.0],
        [9, "ФССЦ-21.1.02.01", "Комплект крепежа, в том числе анкеры",
         "компл", 2, 1, 2, 900.0],
    ]))

    assert names == [
        "Монтаж системы оповещения по СП 484.1311500.2020",
        "Комплект крепежа, в том числе анкеры",
    ]


def test_column_numbers_row_is_still_dropped():
    """Строка с номерами колонок («1 2 3 4 5») позицией не становится.

    Цифры соседних колонок читаются как номер, единица и объём, поэтому смягчать
    её отбрасывание нельзя: иначе в перечне появится позиция с именем «3».
    """
    names = _names(_lsr([
        ["1", "2", "3", "4", "5", "6", "7", "8"],
        [1, "ГЭСН13-06-003-01", "Очистка поверхности щетками", "м2", 12, 1, 12, 8855.27],
    ]))

    assert names == ["Очистка поверхности щетками"]


