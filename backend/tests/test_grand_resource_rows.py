"""Ресурс внутри расценки не должен становиться позицией перечня.

Было: под расценкой ЛСР раскрывается её ресурсная часть — «Н 06.1.01.05 Кирпич
глиняный обыкновенный, 1000 шт, 1,52». У такой строки есть наименование, единица
и объём, поэтому парсер отдавал её Claude наравне с настоящей позицией сметы. А
неучтённый ресурс всегда добавлен ниже отдельной пронумерованной позицией ФССЦ —
и материал уезжал в перечень дважды под двумя названиями.

Стало: позиция сметы — строка с номером в колонке «№ п/п». Всё, что раскрыто
внутри расценки, номера не имеет и в перечень не идёт.
"""
import io

import openpyxl

from app.utils.file_parser import parse_xlsx_grand


def _lsr_with_resources() -> bytes:
    """Расценка с раскрытой ресурсной частью и позиция ФССЦ того же материала.

    Раскладка ГРАНД-Сметы: колонки №, обоснование, наименование, ед., кол-во,
    коэффициенты, всего с учётом коэффициентов, стоимость.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.append(["ЛОКАЛЬНЫЙ СМЕТНЫЙ РАСЧЕТ (СМЕТА) № 1"])
    ws.append(
        ["№ п/п", "Обоснование", "Наименование работ и затрат", "Единица измерения",
         "Количество", "коэффициенты", "всего с учетом коэффициентов", "Сметная стоимость, руб."]
    )
    ws.append(["Раздел 1. Закладка проема"])
    ws.append([123, "ФЕР11-01-011-01", "Устройство стяжек: цементных толщиной 20 мм", "100 м2", 7.666, 1, 7.666, None])
    ws.append([None, "1", "ОТ", None, None, None, None, 78096.15])
    ws.append([None, "2", "ЭМ", None, None, None, None, 4981.25])
    ws.append([None, "4", "М", None, None, None, None, 420.97])
    ws.append(["Н", "04.3.01.09", "Раствор готовый кладочный тяжелый цементный", "м3", 2.04, None, 15.63864, None])
    ws.append([None, None, "ЗТ", "чел.-ч", 35.6, 1.15, 313.84604, None])
    ws.append([None, None, "Итого по расценке", None, None, None, None, 83498.37])
    ws.append([None, None, "Всего по позиции", None, None, None, None, 213404.64])
    ws.append([124, "ФССЦ-04.3.01.09-0015", "Раствор готовый кладочный, цементный, М150", "м3", 15.63864, 1, 15.63864, 55135.13])
    ws.append([None, None, "Всего по позиции", None, None, None, None, 55135.13])
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def _names(rows: list[dict]) -> list[str]:
    return [r["name"] for r in rows if not r["is_section"]]


def test_resource_row_is_not_a_position():
    """Справочный ресурс расценки в перечень не попадает."""
    names = _names(parse_xlsx_grand(_lsr_with_resources()))

    assert "Раствор готовый кладочный тяжелый цементный" not in names


def test_material_position_survives():
    """Настоящая позиция материала остаётся — с объёмом из колонки «всего»."""
    rows = parse_xlsx_grand(_lsr_with_resources())

    material = next(r for r in rows if "М150" in r["name"])
    assert material["unit"] == "м3"
    assert material["quantity"] == 15.63864


def test_no_duplicate_material():
    """Материал уезжает в перечень ровно один раз — это и была жалоба."""
    names = _names(parse_xlsx_grand(_lsr_with_resources()))

    assert len([n for n in names if "аствор" in n]) == 1


def test_work_and_section_survive():
    """Работа и заголовок раздела на месте: чистим только внутренности расценки."""
    rows = parse_xlsx_grand(_lsr_with_resources())

    assert _names(rows) == [
        "Устройство стяжек: цементных толщиной 20 мм",
        "Раствор готовый кладочный, цементный, М150",
    ]
    assert [r["name"] for r in rows if r["is_section"]] == ["Раздел 1. Закладка проема"]


def test_sheet_without_numbering_keeps_all_rows():
    """Нумерации на листе нет — фильтр не включается, лист не пустеет."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.append(["Ведомость объёмов работ"])
    ws.append(["Наименование работ и затрат", "Ед. изм.", "Количество"])
    ws.append(["Устройство стяжек цементных", "100 м2", 7.666])
    ws.append(["Раствор готовый кладочный, цементный, М150", "м3", 15.63864])
    buf = io.BytesIO()
    wb.save(buf)

    names = _names(parse_xlsx_grand(buf.getvalue()))
    assert names == ["Устройство стяжек цементных", "Раствор готовый кладочный, цементный, М150"]


def test_unnumbered_row_with_own_cost_survives():
    """Строка без номера, но со своей стоимостью — позиция, а не ресурс.

    У справочного ресурса ГРАНД-Сметы стоимости не бывает: она уже внутри
    расценки. Если стоимость есть — материал учтён отдельно, и терять его нельзя.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.append(["ЛОКАЛЬНЫЙ СМЕТНЫЙ РАСЧЕТ (СМЕТА) № 1"])
    ws.append(["№ п/п", "Обоснование", "Наименование работ и затрат", "Ед. изм.", "Количество", "Сметная стоимость, руб."])
    ws.append([1, "ФЕР11-01-011-01", "Устройство стяжек цементных", "100 м2", 7.666, 213404.64])
    ws.append([2, "ФЕР46-02-007-01", "Кладка отдельных участков кирпичных стен", "м3", 3.8, 40440.11])
    ws.append([3, "ФЕР08-02-001-01", "Кладка стен кирпичных наружных", "м3", 18.4, 51000.0])
    ws.append([None, "ФССЦ-04.3.01.09-0015", "Раствор готовый кладочный, цементный, М150", "м3", 15.63864, 55135.13])
    buf = io.BytesIO()
    wb.save(buf)

    assert "Раствор готовый кладочный, цементный, М150" in _names(parse_xlsx_grand(buf.getvalue()))
