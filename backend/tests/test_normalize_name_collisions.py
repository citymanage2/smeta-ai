"""Нормализация имени не имеет права склеивать разные позиции.

План `plans/2026-09-02-normalizaciya-imen-prayса.md`.

`normalize_name` — это текст, из которого считается вектор позиции, и по нему же
ищется «эта позиция уже есть» при записи прайса файлом. Пока правило марки
материала съедало слова между первой буквой и первым числом, пароизоляция и
гидроизоляция, ГКЛО и ГКЛВ, ЦЕМ I и ЦЕМ II получали один и тот же ключ — то
есть один и тот же вектор. В смету подставлялась цена не того материала, а при
загрузке прайса файлом пять цен из шести терялись молча.

Пары здесь — не выдуманные: все взяты из `прайс_материалов.xlsx`,
`прайс_работ.xlsx` и сводной сметы РЖД.
"""
import pytest

from app.services.embedding_service import normalize_name


@pytest.mark.parametrize("first, second", [
    # прайс_работ.xlsx
    ("Монтаж рукава металлического до 32мм", "Монтаж пластиковых труб до 32мм"),
    # прайс_материалов.xlsx
    ("Цемент ЦЕМ I 42,5 Н 50 кг", "Цемент ЦЕМ II 42,5 Н 50 кг"),
    ("Пленка гидроизоляционная Изоспан A 1,6х50 м",
     "Пленка пароизоляционная Изоспан B 1,6х50 м"),
    ("Лист гипсокартонный огнестойкий ГКЛО 2500х1200х12,5 KNAUF",
     "Лист гипсокартонный влагостойкий ГКЛВ 2500х1200х12,5 KNAUF"),
    # Сводная РЖД Техническая 87.xlsx
    ("Планка карнизная фальц 0,5 Satin Matt RAL 6005",
     "Планка ендовы нижняя 0,5 Satin Matt RAL 6005"),
    ("Планка капельник 0,5 Satin Matt RAL 6005",
     "Планка примыкание к стене фальц 0,5 Satin Matt RAL 6005"),
    ("Профиль ПН 75×50х3000, Кнауф", "Профиль ПС 75×50х3000, Кнауф"),
    ("Кабель витая пара U/UTP 4х2х0,52, категория 5e",
     "Кабель витая пара U/UTP 2х2х0,52, категория 5e"),
])
def test_different_positions_keep_different_keys(first, second):
    """Разные материалы — разные ключи. Иначе в смету уедет чужая цена."""
    assert normalize_name(first) != normalize_name(second)


@pytest.mark.parametrize("written_as", ["М-100", "М 100", "M100", "м100", "M-100"])
def test_material_grade_still_collapses(written_as):
    """Ради чего правило и заводилось: марка пишется как угодно, ключ один."""
    assert normalize_name(written_as) == "м100"


def test_grade_rule_does_not_eat_words():
    """Слова между буквой и числом остаются на месте.

    Именно их проглатывание («Пленка ... Изоспан A 1,6») и превращало название
    в огрызок «п1,6х50 м».
    """
    assert normalize_name("Пленка гидроизоляционная Изоспан A 1,6х50 м") \
        .startswith("пленка гидроизоляционная изоспан")


def test_case_and_spaces_still_normalized():
    """Прежние свойства никуда не делись."""
    assert normalize_name("  Кладка  кирпичная  ") == "кладка кирпичная"
    assert normalize_name("") == ""


def test_reference_price_uses_the_same_key():
    """Эталонный прайс не заводит второго определения «та же позиция».

    До 02.09.2026 `reference_price` считал ключ сам — потому что общей
    нормализации нельзя было доверять. Теперь правило одно на все пути записи
    в прайс: иначе эталон заводил бы вторую строку там, где загрузка файлом
    сливает две («Раствор М-100» и «Раствор М 100»).
    """
    from app.services.reference_price import match_key

    assert match_key("Раствор М-100") == normalize_name("Раствор М 100")
    assert match_key("Изоспан A 1,6х50 м") != match_key("Изоспан B 1,6х50 м")
